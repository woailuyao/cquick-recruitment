"""配置读写：优先 pyyaml，缺失时用内置极简实现（只支持本工程用到的结构）。"""
from __future__ import annotations

import math
import os
from typing import Any, Optional

import numpy as np


def _load_yaml(path: str) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    try:
        import yaml  # type: ignore
        data = yaml.safe_load(text)
        return data if isinstance(data, dict) else {}
    except Exception:
        return _parse_flat(text)


def _parse_value(v: str):
    """解析标量或（可嵌套的）行内列表。"""
    v = v.strip()
    if v.startswith("[") and v.endswith("]"):
        inner = v[1:-1]
        parts, depth, cur = [], 0, ""
        for ch in inner:
            if ch in "[{":
                depth += 1
            elif ch in "]}":
                depth -= 1
            if ch == "," and depth == 0:
                parts.append(cur)
                cur = ""
            else:
                cur += ch
        if cur.strip():
            parts.append(cur)
        return [_parse_value(p) for p in parts if p.strip()]
    try:
        return float(v)
    except ValueError:
        pass
    low = v.lower()
    if low in ("true", "yes", "on"):
        return True
    if low in ("false", "no", "off"):
        return False
    if low in ("null", "none", "~"):
        return None
    return v.strip("\"'")


def _as_bool(v, default: bool = False) -> bool:
    if isinstance(v, bool):
        return v
    if isinstance(v, str):
        return v.strip().lower() in ("true", "yes", "on", "1")
    if v is None:
        return default
    return bool(v)


def _parse_flat(text: str) -> dict:
    """极简 YAML 兜底（支持两层嵌套 + 行内嵌套列表），pyyaml 缺失时使用。"""
    root: dict = {}
    stack = [(-1, root)]
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].rstrip()
        if not line.strip() or ":" not in line:
            continue
        indent = len(line) - len(line.lstrip())
        while len(stack) > 1 and indent <= stack[-1][0]:
            stack.pop()
        parent = stack[-1][1]
        k, v = line.strip().split(":", 1)
        k, v = k.strip(), v.strip()
        if v == "":
            child: dict = {}
            parent[k] = child
            stack.append((indent, child))
            continue
        parent[k] = _parse_value(v)
    return root


def _dump(obj: Any, indent: int = 0) -> str:
    pad = "  " * indent
    if isinstance(obj, dict):
        lines = []
        for k, v in obj.items():
            if isinstance(v, (dict, list)) and not _is_flat_list(v):
                lines.append(f"{pad}{k}:")
                lines.append(_dump(v, indent + 1))
            else:
                lines.append(f"{pad}{k}: {_inline(v)}")
        return "\n".join(lines)
    if isinstance(obj, list):
        if _is_flat_list(obj):
            return f"{pad}{_inline(obj)}"
        lines = []
        for v in obj:
            if isinstance(v, list) and not _is_flat_list(v):
                lines.append(f"{pad}-")
                lines.append(_dump(v, indent + 1))
            else:
                lines.append(f"{pad}- {_inline(v)}")
        return "\n".join(lines)
    return f"{pad}{_inline(obj)}"


def _is_flat_list(v) -> bool:
    if not isinstance(v, list):
        return False
    return all(not isinstance(x, (dict, list)) for x in v) or (
        all(isinstance(x, list) and all(not isinstance(y, (dict, list)) for y in x)
            for x in v)
        and isinstance(v, list) and all(isinstance(x, list) for x in v)
    )


def _inline(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.10g}"
    if isinstance(v, np.ndarray):
        return _inline(v.tolist())
    if isinstance(v, list):
        return "[ " + ", ".join(_inline(x) for x in v) + " ]"
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "null"
    if isinstance(v, str):
        return '"' + v.replace('"', "'") + '"'
    return str(v)


def save_yaml(path: str, data: dict) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    text = "# generated by cquick_vision\n" + _dump(data) + "\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


# --------------------------------------------------------------- 专用加载器

def load_intrinsics(path: str) -> dict:
    d = _load_yaml(path)
    K = np.asarray(d.get("camera_matrix"), float).reshape(3, 3)
    dist = np.asarray(d.get("dist_coeffs", [0, 0, 0, 0, 0]), float).reshape(-1)
    return {
        "K": K,
        "dist": dist,
        "fy": float(K[1, 1]),
        "fx": float(K[0, 0]),
        "width": int(d.get("image_width", 1280)),
        "height": int(d.get("image_height", 720)),
        "calibrated": _as_bool(d.get("calibrated", False)),
        "rms": float(d.get("rms_reprojection_error_px", 0.0) or 0.0),
        "raw": d,
    }


def load_extrinsics(path: str) -> dict:
    d = _load_yaml(path)
    R = np.asarray(d.get("rotation"), float).reshape(3, 3)
    t = np.asarray(d.get("translation"), float).reshape(3)
    return {
        "R": R,
        "t": t,
        "height": float(d.get("camera_height_m", t[2])),
        "pitch_deg": float(d.get("pitch_deg_down", 0.0)),
        "roll_deg": float(d.get("roll_deg", 0.0)),
        "yaw_offset_deg": float(d.get("camera_yaw_offset_deg", 0.0)),
        "frame": str(d.get("frame", "base_link")),
        "calibrated": _as_bool(d.get("calibrated", False)),
        "raw": d,
    }


def load_matching(path: str) -> dict:
    return _load_yaml(path)


def require(cond: bool, msg: str) -> None:
    if not cond:
        raise SystemExit("[配置检查失败] " + msg)


def sanity_check(intr: dict, extr: dict, verbose: bool = True) -> None:
    """启动时的硬性检查，避免带着占位参数跑出假结果。"""
    if not intr["calibrated"]:
        print("[WARN] 内参标记为未标定（calibration/camera_intrinsics.yaml），"
              "结果不可用于验收。")
    if intr["rms"] > 1.0:
        print(f"[WARN] 内参重投影误差 {intr['rms']:.2f}px 偏大（建议 <0.5px）。")
    if not extr["calibrated"]:
        print("[WARN] 外参标记为未标定（calibration/camera_extrinsics.yaml），"
              "地面投影精度不可信。")
    if extr["height"] <= 0.05:
        raise SystemExit("[配置检查失败] 相机离地高度异常，请检查 camera_extrinsics.yaml")
    R = extr["R"]
    if abs(float(np.linalg.det(R)) - 1.0) > 1e-3:
        raise SystemExit("[配置检查失败] 外参旋转矩阵行列式不是 1，不是有效旋转")
    if verbose:
        print(f"[cfg] fx={intr['fx']:.2f} fy={intr['fy']:.2f} "
              f"cx={intr['K'][0,2]:.2f} cy={intr['K'][1,2]:.2f} "
              f"rms={intr['rms']:.3f}px")
        print(f"[cfg] h={extr['height']:.3f}m pitch={extr['pitch_deg']:.2f} "
              f"roll={extr['roll_deg']:.2f} yaw_off={extr['yaw_offset_deg']:.2f} "
              f"frame={extr['frame']}")


def deg2rad(d: float) -> float:
    return float(d) * math.pi / 180.0
