import cv2
import os
img=cv2.imread("photo2.jpg")
os.makedirs("outputs",exist_ok=True)
if img is None:
    print("输入失败")
else:
    cv2.imshow("origina",img)
    cv2.waitKey(0)
    gray=cv2.cvtColor(img,cv2.COLOR_BGR2GRAY)
    cv2.imwrite("outputs_gray.jpg",gray)
    cv2.imshow("gray",gray)
    cv2.waitKey(0)
    gauss=cv2.GaussianBlur(gray,(3,3),0)
    cv2.imwrite("outputs_gauss.jpg",gauss)
    cv2.imshow("gauss",gauss)
    cv2.waitKey(0)
    ret,thresh=cv2.threshold(gauss,127,255,cv2.THRESH_BINARY)
    cv2.imwrite("outputs_thresh.jpg",thresh)
    cv2.imshow("thresh",thresh)
    cv2.waitKey(0)
    canny=cv2.Canny(gauss,50,150)
    cv2.imwrite("outputs_canny.jpg",canny)
    cv2.imshow("canny",canny)
    cv2.waitKey(0)
    kernel=cv2.getStructuringElement(cv2.MORPH_RECT,(3,3))
    morph=cv2.morphologyEx(thresh,cv2.MORPH_OPEN,kernel)
    cv2.imwrite("outputs_morph.jpg",morph)
    cv2.imshow("morph",morph)
    cv2.waitKey(0)
