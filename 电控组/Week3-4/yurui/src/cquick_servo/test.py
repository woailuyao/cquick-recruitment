#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
test_servo.py —— 手动调试舵机的工具（不依赖 ROS2，单独就能跑）

它能干嘛：
  连上串口 → 给舵机发指令 → 把回显打印出来 → 支持循环、支持一次测多个舵机。

整个文件分三块，从上往下看：
  【区域 1】收发函数  —— 发一条、收一条，写一次以后一直调用
  【区域 2】配置区    —— 串口、ID、指令全在这里改（你主要动这一块）
  【区域 3】主程序    —— 循环发、打印回显（看懂就行，一般不用改）

你 90% 的时间只需要改【区域 2】，把那块看懂就够了。
"""

import time
import serial

# =====================================================================
# 【区域 1】收发函数
# ---------------------------------------------------------------------
# send_and_receive(串口, 指令, 等多久)
#   作用：发一条指令给舵机，再把舵机回的话读回来
#   返回：回显的文字
# 这个函数写一次就行，后面直接调用，不用每次重写。
# =====================================================================
def send_and_receive(ser, command, wait=0.1):
    # 1) 发：字符串转成字节（.encode()），写进串口
    ser.write(command.encode("ascii"))
    ser.flush()

    # 2) 等：给舵机一点反应时间
    time.sleep(wait)

    # 3) 收：把串口里攒的回显全部读出来
    reply = b""
    while ser.in_waiting > 0:
        reply += ser.read(ser.in_waiting)
        time.sleep(0.01)

    # 4) 字节转成文字，返回给调用的人
    return reply.decode("ascii", "ignore").strip()


# =====================================================================
# 【区域 2】配置区 —— 所有可能改的东西都集中在这里
# ---------------------------------------------------------------------
# 换串口、换舵机、改指令、改循环次数，全部在这一块改，别动别的地方。
# =====================================================================

# --- 串口 ---
PORT = "/dev/ttyUSB0"     # 虚拟串口写 "/tmp/ttyFAKE"，真舵机写 "/dev/ttyUSB0"
BAUD = 115200             # 波特率固定 115200，别改

# --- 要给哪些舵机发指令 ---
SERVO_IDS = [1,2,3,4,5,6,7,8,9,0]     # 只测一个就写 [0]；全测写 [1,2,3,4,5,6,7,8,9,0]

# --- 发什么指令（这里最容易改）---
# 每个舵机会依次发下面这几条；{id} 会自动换成舵机号
# 想改动作就改这些字符串，或者加一行、删一行

# "#{id:03d}PULR!",           # 恢复扭力（要它动之前必须先发这条）
# "#{id:03d}PULK!",           # 卸去扭力
# "#{id:03d}P1500T1000!",     # 转到中位 1500，用时 1000 ms
# "#{id:03d}PRAD!",           # 读回当前位置
# "#{id:03d}p"

COMMANDS = [
    #"#{id:03d}PULR!",           # 恢复扭力（要它动之前必须先发这条）
    "#{id:03d}PULK!",
    #"#{id:03d}P1500T1000!",     # 转到中位 1500，用时 1000 ms
    #"#{id:03d}PRAD!",           # 读回当前位置
]

# --- 每条指令之间等多久（秒）---
WAIT = 0.5

# --- 整个流程重复几遍 ---
REPEAT = 1                # 想连测三遍就写 3


# =====================================================================
# 【区域 3】主程序 —— 循环发指令，打印回显
# ---------------------------------------------------------------------
# 看懂就行，一般不用改。
# =====================================================================
def main():
    ser = serial.Serial(PORT, BAUD, timeout=0.1)
    print(f"串口 {PORT} 已连接，波特率 {BAUD}")
    print(f"舵机：{SERVO_IDS}，每条间隔 {WAIT}s，重复 {REPEAT} 遍")
    print("=" * 55)

    for round_no in range(1, REPEAT + 1):
        print(f"—— 第 {round_no} 遍 ——")
        for sid in SERVO_IDS:
            for template in COMMANDS:
                cmd = template.format(id=sid)          # 把 {id} 换成当前舵机号
                reply = send_and_receive(ser, cmd, WAIT)
                print(f"  ID {sid:03d}  发 [{cmd:20}]  收 [{reply}]")
                
        print()

    ser.close()
    print("=" * 55)
    print("完成，串口已关闭")


if __name__ == "__main__":
    main()
